/// Generated image.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ImageData {
    /// Base64-encoded image data.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub b64_json: Option<String>,
    /// Raw image. Only populated for the `raw` output format.
    #[serde(skip)]
    pub image: Option<Image>,
}

/// Token usage for an image generation request.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ImageUsage {
    /// Number of tokens (images and text) in the input prompt.
    pub input_tokens: u64,
    /// Number of output tokens generated by the model.
    pub output_tokens: u64,
    /// Total number of tokens (images and text) used for the image generation.
    pub total_tokens: u64,
}

/// Image generation response.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ImageResponse {
    /// The list of generated images.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub data: Option<Vec<ImageData>>,
    /// The background parameter used for the image generation.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub background: Option<String>,
    /// Unix timestamp, in seconds, when the image was created.
    pub created: i64,
    /// Token usage information for the image generation.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub usage: Option<ImageUsage>,
}

/// Signature-resolved image inputs and response conversion.
#[derive(Debug, Clone)]
pub struct OpenAIImageGenerationAdapter {
    pub prompt: Parameter,
    pub output: usize,
    pub count: Option<Parameter>,
    pub width: Option<Parameter>,
    pub height: Option<Parameter>,
}

impl OpenAIImageGenerationAdapter {
    /// Returns `None` when the signature is incompatible or ambiguous.
    pub fn from_signature(signature: &Signature) -> Option<Self> {
        // Prompt parameter.
        let prompt = parameter(
            &signature.inputs,
            &[Dtype::String],
            Some("openai.images.prompt"),
        )
        .ok()??;
        // Optional generation width.
        let width = parameter(&signature.inputs, INTEGERS, Some("openai.images.width")).ok()?;
        if width
            .as_ref()
            .is_some_and(|parameter| parameter.optional != Some(true))
        {
            return None;
        }
        // Optional generation height.
        let height = parameter(&signature.inputs, INTEGERS, Some("openai.images.height")).ok()?;
        if height
            .as_ref()
            .is_some_and(|parameter| parameter.optional != Some(true))
        {
            return None;
        }
        // Optional generation count.
        let count = parameter(&signature.inputs, INTEGERS, Some("openai.images.count")).ok()?;
        if count
            .as_ref()
            .is_some_and(|parameter| parameter.optional != Some(true))
        {
            return None;
        }
        validate_inputs(
            signature,
            &[
                Some(&prompt),
                width.as_ref(),
                height.as_ref(),
                count.as_ref(),
            ],
        )
        .ok()?;
        // Image output.
        let (output, _) = get_parameter(&signature.outputs, &[Dtype::ImageList], None).ok()??;
        Some(Self {
            prompt,
            output,
            count,
            width,
            height,
        })
    }

    pub fn inputs(
        &self,
        prompt: String,
        n: Option<i32>,
        width: Option<i32>,
        height: Option<i32>,
    ) -> HashMap<String, Value> {
        let mut inputs = HashMap::new();
        inputs.insert(self.prompt.name.clone(), Value::String(prompt));
        if let (Some(parameter), Some(value)) = (&self.count, n) {
            inputs.insert(parameter.name.clone(), Value::Int(value));
        }
        if let (Some(parameter), Some(value)) = (&self.width, width) {
            inputs.insert(parameter.name.clone(), Value::Int(value));
        }
        if let (Some(parameter), Some(value)) = (&self.height, height) {
            inputs.insert(parameter.name.clone(), Value::Int(value));
        }
        inputs
    }
}

#[async_trait]
impl Adapter for OpenAIImageGenerationAdapter {
    type Source = Prediction;
    type Options = OpenAIImageOptions;
    type Response = ImageResponse;

    fn kind(&self) -> &'static str {
        "openai.images.generate"
    }

    async fn adapt(
        &self,
        prediction: Prediction,
        options: Option<Self::Options>,
    ) -> Result<ImageResponse> {
        image_response(&prediction, self.output, options.unwrap_or_default()).await
    }
}

#[derive(Debug, Clone)]
pub struct OpenAIImageOptions {
    pub output_format: String,
    pub output_compression: Option<i32>,
}

impl Default for OpenAIImageOptions {
    fn default() -> Self {
        Self {
            output_format: "png".into(),
            output_compression: None,
        }
    }
}

pub(crate) async fn image_response(
    prediction: &Prediction,
    output: usize,
    options: OpenAIImageOptions,
) -> Result<ImageResponse> {
    if !matches!(
        options.output_format.as_str(),
        "png" | "jpeg" | "webp" | "raw"
    ) || options
        .output_compression
        .is_some_and(|quality| !(0..=100).contains(&quality))
    {
        return Err(MunaError::InvalidInput(
            "Invalid image encoding options".into(),
        ));
    }
    let value = result(prediction, output)?;
    let images = match value {
        Value::Remote(remote) if remote.dtype == Dtype::ImageList => match &remote.data {
            Some(crate::types::RemoteData::Sequence(images)) => {
                images.iter().cloned().map(Value::Remote).collect()
            }
            _ => match decode(value, Dtype::ImageList).await? {
                Value::ImageList(images) => images.into_iter().map(Value::Image).collect(),
                _ => return Err(MunaError::Prediction("Expected image_list output".into())),
            },
        },
        Value::ImageList(images) => images.iter().cloned().map(Value::Image).collect::<Vec<_>>(),
        _ => return Err(MunaError::Prediction("Expected image_list output".into())),
    };
    if images.is_empty() {
        return Err(MunaError::Prediction(
            "Image predictor must return a nonempty image list".into(),
        ));
    }
    let mut data = Vec::with_capacity(images.len());
    for image in images {
        // Matching inline encodings never enter the native decoder.
        if let Value::Remote(remote) = &image {
            if remote.dtype != Dtype::Image {
                return Err(MunaError::Prediction(
                    "Each result must have dtype image".into(),
                ));
            }
            if let Some(payload) =
                inline_base64(remote, &[&format!("image/{}", options.output_format)])
            {
                data.push(ImageData {
                    b64_json: Some(payload.to_string()),
                    image: None,
                });
                continue;
            }
        }
        let Value::Image(image) = decode(&image, Dtype::Image).await? else {
            return Err(MunaError::Prediction("Expected image result".into()));
        };
        data.push(encode_image(
            &image,
            &options.output_format,
            options.output_compression,
        )?);
    }
    Ok(ImageResponse {
        data: Some(data),
        background: None,
        created: created(prediction)?,
        usage: None,
    })
}

pub(crate) fn encode_image(
    image: &crate::types::Image,
    output_format: &str,
    quality: Option<i32>,
) -> Result<ImageData> {
    use base64::{engine::general_purpose::STANDARD as BASE64, Engine};
    if output_format == "raw" {
        return Ok(ImageData {
            b64_json: None,
            image: Some(image.clone()),
        });
    }
    let mut mime = format!("image/{output_format}");
    if let Some(quality) = quality {
        mime.push_str(&format!(";q={:.2}", quality as f32 / 100.0));
    }
    let bytes =
        crate::c::Value::from_object(&Value::Image(image.clone()))?.serialize(Some(&mime))?;
    Ok(ImageData {
        b64_json: Some(BASE64.encode(bytes)),
        image: None,
    })
}
